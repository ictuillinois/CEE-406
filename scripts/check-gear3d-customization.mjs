 assert.equal(project.view.bodyOpacity,60);assert.equal(project.view.bodyColor,'#a6774f');
 await page.locator('#g3-file-input').setInputFiles({name:'custom.gear3d',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(project))});
