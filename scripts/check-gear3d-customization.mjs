 await page.locator('#g3-body-reset').click();
 assert.deepEqual(await page.evaluate(()=>[gear3d.store.view.bodyOpacity,gear3d.store.view.bodyColor]),[28,'#71899b']);
 assert.equal(await page.locator('[data-body-opacity="28"]').getAttribute('aria-pressed'),'true');
 await page.locator('#g3-domain').selectOption('aircraft');assert.equal(await page.locator('#g3-wbt-apply').isDisabled(),true);
 assert.deepEqual(errors,[]);console.log('PASS: direct axle selection, WBT/DTA restoration, saved original, appearance persistence, mesh reuse, undo/redo and aircraft state');
